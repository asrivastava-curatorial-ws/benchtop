#!/usr/bin/env node
/**
 * Builds src/lib/elements-data.ts from two MIT-licensed packages:
 *   periodic-table-data 1.1.1 (PubChem's periodic table)  → periodicTableData.json
 *   chemical-elements 2.3.3 (cheminfo)                     → lib/src/elementsAndIsotopes.js
 * The isotope file is read as text (never run): only stable isotopes with an
 * abundance are kept.
 *
 *   node scripts/elements-table.mjs <periodicTableData.json> <elementsAndIsotopes.js>
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [tablePath, isotopePath] = process.argv.slice(2);
if (!tablePath || !isotopePath) {
  console.error('usage: node scripts/elements-table.mjs <periodicTableData.json> <elementsAndIsotopes.js>');
  process.exit(1);
}
const table = JSON.parse(readFileSync(tablePath, 'utf8'));
const source = readFileSync(isotopePath, 'utf8');

/** number → [[mass number, abundance], ...] */
const isotopes = new Map();
for (const block of source.split(/\n\s{4}\{\n/).slice(1)) {
  const number = Number(/number:\s*(\d+)/.exec(block)?.[1]);
  if (!number) continue;
  const stable = [];
  for (const m of block.matchAll(/\{\s*nominal:\s*(\d+),\s*mass:\s*[\d.]+,\s*abundance:\s*([\d.e-]+)\s*\}/g)) stable.push([Number(m[1]), Number(m[2])]);
  isotopes.set(number, stable);
}

const STATE = { Gas: 'g', Liquid: 'l', Solid: 's', 'Expected to be a Gas': 'g?', 'Expected to be a Solid': 's?' };
const rows = table.map((e) => [
  e.atomicNumber,
  e.symbol,
  e.name,
  e.atomicMass,
  e.cPKHexColor ?? '',
  e.electronConfiguration ?? '',
  e.electronegativity ?? null,
  e.atomicRadius ?? null,
  e.ionizationEnergy ?? null,
  e.electronAffinity ?? null,
  e.oxidationStates ?? '',
  STATE[e.standardState] ?? '',
  e.meltingPoint ?? null,
  e.boilingPoint ?? null,
  e.density ?? null,
  e.groupBlock ?? '',
  e.yearDiscovered ?? '',
  isotopes.get(e.atomicNumber) ?? [],
]);
if (rows.length !== 118) throw new Error(`Expected 118 elements, found ${rows.length}`);

const out = `/**
 * The 118 elements: PubChem's periodic table (public domain, packaged as
 * periodic-table-data 1.1.1, MIT) with stable isotopes and their abundances
 * from chemical-elements 2.3.3 (cheminfo, MIT).  Generated by
 * scripts/elements-table.mjs; do not edit by hand.
 *
 * Each row: number, symbol, name, atomic mass, CPK colour, electron
 * configuration, electronegativity (Pauling), atomic radius (pm), ionisation
 * energy (eV), electron affinity (eV), oxidation states, standard state
 * (s, l, g; "?" when predicted), melting point (K), boiling point (K),
 * density (g/cm³), category, year discovered, stable isotopes [A, abundance].
 */
export type ElementRow = readonly [
  number,
  string,
  string,
  number,
  string,
  string,
  number | null,
  number | null,
  number | null,
  number | null,
  string,
  string,
  number | null,
  number | null,
  number | null,
  string,
  string,
  readonly (readonly [number, number])[],
];

export const ELEMENT_ROWS: readonly ElementRow[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../src/lib/elements-data.ts', import.meta.url), out);
console.log(`Wrote ${rows.length} elements; ${[...isotopes.values()].filter((l) => l.length).length} with stable isotopes.`);
