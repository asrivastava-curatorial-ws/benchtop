"""Evaluate CoolProp saturation ancillaries and emit a compact TypeScript data module.

Usage: python3 -I refrigerant_table.py <fluids dir> [--check] [--emit out.ts]
Reads only the JSON files named below from the given directory.
"""
import json
import math
import sys
from pathlib import Path

# id, file stem, label, kind of glide
FLUIDS = [
    ("R32", "R32", "R-32"),
    ("R410A", "R410A", "R-410A"),
    ("R22", "R22", "R-22"),
    ("R134a", "R134a", "R-134a"),
    ("R290", "n-Propane", "R-290 (propane)"),
    ("R600a", "IsoButane", "R-600a (isobutane)"),
    ("R1234yf", "R1234yf", "R-1234yf"),
    ("R1234ze", "R1234ze(E)", "R-1234ze(E)"),
    ("R404A", "R404A", "R-404A"),
    ("R407C", "R407C", "R-407C"),
    ("R507A", "R507A", "R-507A"),
    ("R717", "Ammonia", "R-717 (ammonia)"),
    ("R744", "CarbonDioxide", "R-744 (CO₂)"),
    ("R1233zd", "R1233zd(E)", "R-1233zd(E)"),
]


def ancillary(spec):
    n, t = spec["n"], spec["t"]
    tr, pr = spec["T_r"], spec["reducing_value"]
    tau = spec.get("using_tau_r", False)

    def pressure(kelvin):
        theta = 1 - kelvin / tr
        total = sum(ni * theta**ti for ni, ti in zip(n, t))
        if tau:
            total *= tr / kelvin
        return pr * math.exp(total)

    return pressure


def load(folder, stem):
    with open(Path(folder) / f"{stem}.json", encoding="utf-8") as handle:
        data = json.load(handle)
    anc = data["ANCILLARIES"]
    crit = data["STATES"]["critical"]
    if "pS" in anc:
        bubble = dew = ancillary(anc["pS"])
        source = anc["pS"]
    else:
        bubble, dew = ancillary(anc["pL"]), ancillary(anc["pV"])
        source = anc["pL"]
    tmin = max(source["Tmin"], data["EOS"][0]["Ttriple"])
    return data, bubble, dew, crit["T"], tmin


CHECKS = {
    # (fluid, °C): expected kPa abs (bubble, dew) from published saturation tables
    ("R134a", 0): (292.8, 292.8),
    ("R134a", 40): (1016.6, 1016.6),
    ("R22", 0): (497.6, 497.6),
    ("R22", 40): (1533.6, 1533.6),
    ("R32", 0): (813.1, 813.1),
    ("R290", 0): (474.5, 474.5),
    ("R600a", 0): (156.9, 156.9),
    ("R717", 0): (429.4, 429.4),
    ("R744", 0): (3485.1, 3485.1),
    ("R1234yf", 0): (316.0, 316.0),
    ("R410A", 0): (800.0, 798.0),
}


def main():
    folder = sys.argv[1]
    rows = {}
    for fid, stem, label in FLUIDS:
        data, bubble, dew, tc, tmin = load(folder, stem)
        rows[fid] = (label, bubble, dew, tc, tmin, data)
    if "--check" in sys.argv:
        for (fid, celsius), (eb, ed) in CHECKS.items():
            _, bubble, dew, *_ = rows[fid]
            k = celsius + 273.15
            print(f"{fid:8} {celsius:4} °C bubble {bubble(k)/1000:8.1f} (table {eb})  dew {dew(k)/1000:8.1f} (table {ed})")
        for fid in ("R404A", "R407C", "R507A", "R410A"):
            label, bubble, dew, tc, tmin, data = rows[fid]
            for celsius in (-40, -20, 0, 20, 40):
                k = celsius + 273.15
                print(f"{fid:8} {celsius:4} °C bubble {bubble(k)/1000:8.1f} dew {dew(k)/1000:8.1f}")
            print("   ", data["ANCILLARIES"]["pL"].get("description", "")[:200])
    if "--emit" in sys.argv:
        out = sys.argv[sys.argv.index("--emit") + 1]
        lines = [
            "/**",
            " * Refrigerant saturation curves, generated by scripts/refrigerant_table.py from the",
            " * saturation-pressure ancillary equations in CoolProp's fluid files (MIT licence).",
            " * Each entry: ln(p / pr) = (Tr / T) · Σ nᵢ θ^tᵢ with θ = 1 − T / Tr, p in Pa, T in K.",
            " * Blends carry separate bubble (liquid) and dew (vapour) equations.",
            " */",
            "",
            "export interface Ancillary {",
            "  readonly tr: number;",
            "  readonly pr: number;",
            "  readonly n: readonly number[];",
            "  readonly t: readonly number[];",
            "}",
            "",
            "export interface Refrigerant {",
            "  readonly id: string;",
            "  readonly label: string;",
            "  /** Critical temperature, K. */",
            "  readonly tc: number;",
            "  /** Lowest temperature the equation covers, K. */",
            "  readonly tmin: number;",
            "  readonly bubble: Ancillary;",
            "  /** Absent for pure fluids and azeotropes: the dew curve equals the bubble curve. */",
            "  readonly dew?: Ancillary;",
            "}",
            "",
            "export const REFRIGERANTS: readonly Refrigerant[] = [",
        ]

        def fmt(spec):
            n = ", ".join(repr(round(v, 12)) for v in spec["n"])
            t = ", ".join(repr(round(v, 12)) for v in spec["t"])
            return f"{{ tr: {spec['T_r']}, pr: {spec['reducing_value']}, n: [{n}], t: [{t}] }}"

        for fid, stem, label in FLUIDS:
            data = rows[fid][5]
            anc = data["ANCILLARIES"]
            tc = rows[fid][3]
            tmin = rows[fid][4]
            if "pS" in anc:
                lines.append(f"  {{ id: '{fid}', label: '{label}', tc: {tc}, tmin: {tmin}, bubble: {fmt(anc['pS'])} }},")
            else:
                lines.append(f"  {{ id: '{fid}', label: '{label}', tc: {tc}, tmin: {tmin}, bubble: {fmt(anc['pL'])}, dew: {fmt(anc['pV'])} }},")
        lines.append("];")
        Path(out).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote", out)


if __name__ == "__main__":
    main()
