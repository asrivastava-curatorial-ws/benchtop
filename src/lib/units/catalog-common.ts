/** IAU 2015: 648,000 / π astronomical units. */
const PARSEC = (149597870700 * 648000) / Math.PI;

const PI = Math.PI;
const db = (reference: number, ten: 10 | 20) => ({
  to: (level: number) => reference * 10 ** (level / ten),
  from: (value: number) => ten * Math.log10(value / reference),
});

interface Part {
  readonly symbol: string;
  readonly name: string;
  readonly factor: number;
  readonly id?: string;
}

/** Every "a per b" combination: litres per minute, tonnes per hour… */
function per(top: readonly Part[], bottom: readonly Part[], aliases: Readonly<Record<string, readonly string[]>> = {}): UnitDef[] {
  return top.flatMap((t) =>
    bottom.map((b) => {
      const id = `${t.id ?? t.symbol}/${b.id ?? b.symbol}`;
      return lin(`${t.symbol}/${b.symbol}`, `${t.name} per ${b.name}`, t.factor / b.factor, { id, aliases: aliases[id] });
    }),
  );
}

