const PI = Math.PI;
const level = (reference: number, ten: 10 | 20) => [(l: number) => reference * 10 ** (l / ten), (v: number) => ten * Math.log10(v / reference)] as const;

/** A lab result category: molar and mass units of one substance. */
function analyte(id: string, name: string, molarMass: number, base: 'mmol/L' | 'µmol/L', extra: ReturnType<typeof lin>[] = [], keywords: string[] = []): UnitCategory {
  // Factors give the base unit per one shown unit.
  const perMgDl = base === 'mmol/L' ? 10 / molarMass : 1e4 / molarMass;
  const perMgL = perMgDl / 10;
  const molar =
    base === 'mmol/L'
      ? [lin('mmol/L', 'millimole per litre', 1, { aliases: ['mmol/l', 'mM'] }), lin('µmol/L', 'micromole per litre', 1e-3, { id: 'umol/L', aliases: ['umol/L', 'µM'] })]
      : [lin('µmol/L', 'micromole per litre', 1, { id: 'umol/L', aliases: ['umol/L', 'umol/l', 'µM'] }), lin('mmol/L', 'millimole per litre', 1000, { aliases: ['mmol/l'] })];
  return {
    id,
    name,
    group: 'health',
    description: `${name} results in molar and mass units`,
    keywords: [...keywords, 'lab report', 'blood test'],
    note: `Uses a molar mass of ${molarMass} g/mol. For reading a result in another unit; reference ranges come from the laboratory.`,
    units: [...molar, lin('mg/dL', 'milligram per decilitre', perMgDl, { aliases: ['mg/dl', 'mg%'] }), lin('mg/L', 'milligram per litre', perMgL, { aliases: ['mg/l'] }), ...extra],
  };
}

