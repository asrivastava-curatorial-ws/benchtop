/**
 * Regenerates src/calc/names.ts, the small index of calculators that the
 * app's search uses without loading the library itself:
 *   WRITE_CALC_NAMES=1 pnpm vitest run tests/unit/calc-names.test.ts && pnpm biome format --write src/calc/names.ts
 */
import { writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { CALCULATORS } from '../../src/calc/library';
import { CALCULATOR_NAMES } from '../../src/calc/names';

it('keeps the calculator name index up to date', () => {
  const rows = CALCULATORS.map((c) => [c.id, c.name, c.category, (c.keywords ?? []).join('|')] as const);
  if (process.env.WRITE_CALC_NAMES) {
    const quote = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
    const source = `/** Generated by tests/unit/calc-names.test.ts: [id, name, category, keywords] of every calculator, for search. */\nexport const CALCULATOR_NAMES: readonly (readonly [string, string, string, string])[] = [\n${rows.map((r) => `  [${r.map(quote).join(', ')}],`).join('\n')}\n];\n`;
    writeFileSync(new URL('../../src/calc/names.ts', import.meta.url), source);
    return;
  }
  expect(CALCULATOR_NAMES).toEqual(rows);
});
