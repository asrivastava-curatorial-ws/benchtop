/**
 * Regenerates src/recipe/names.ts, the small list of Recipe operations that
 * the app's search uses without loading the operations themselves:
 *   WRITE_RECIPE_NAMES=1 pnpm vitest run tests/unit/recipe-names.test.ts
 */
import { writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { OPERATIONS } from '../../src/recipe/catalog';

it('writes the operation name index', () => {
  const rows = OPERATIONS.map((op) => `  [${JSON.stringify(op.id)}, ${JSON.stringify(op.name)}, ${JSON.stringify(op.category)}],`);
  const source = `/** Generated by tests/unit/recipe-names.test.ts: [id, name, category] of every Recipe operation, for search. */\nexport const OPERATION_NAMES: readonly (readonly [string, string, string])[] = [\n${rows.join('\n')}\n];\n`;
  if (process.env.WRITE_RECIPE_NAMES) writeFileSync(new URL('../../src/recipe/names.ts', import.meta.url), source);
  expect(rows.length).toBeGreaterThan(0);
});
