#!/usr/bin/env node
// Writes the compiled examples (HEX) and their sketches into a TypeScript module.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [sources, compiled, out] = process.argv.slice(2);
const examples = readdirSync(sources)
  .filter((f) => f.endsWith('.ino'))
  .sort()
  .map((file) => {
    const id = file.replace(/\.ino$/, '');
    return { id, sketch: readFileSync(join(sources, file), 'utf8'), hex: readFileSync(join(compiled, `${id}.hex`), 'utf8') };
  });
const body = `/**
 * Example sketches for the Arduino Uno in the circuit simulator, compiled
 * with avr-gcc and Benchtop's small Arduino-style core (firmware/avr).
 * Generated by firmware/avr/build-examples.sh; do not edit by hand.
 */
export interface UnoExample {
  readonly id: string;
  readonly sketch: string;
  readonly hex: string;
}

export const UNO_EXAMPLES: readonly UnoExample[] = ${JSON.stringify(examples, null, 2)};
`;
writeFileSync(out, body);
console.log(`Wrote ${examples.length} examples to ${out}`);
