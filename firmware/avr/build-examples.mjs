#!/usr/bin/env node
/*
 * Builds the example sketches for the simulator's AVR boards with avr-gcc,
 * Benchtop's small Arduino-style core (core/) and the libraries the sketches
 * include (libraries/), and writes src/lib/circuit/avr-examples.ts with each
 * sketch and its Intel HEX.  Needs gcc-avr and avr-libc:
 *   node firmware/avr/build-examples.mjs
 * examples/uno builds for the ATmega328P (Uno and Nano), examples/mega for
 * the ATmega2560 and examples/tiny for the ATtiny85 at 8 MHz.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const CHIPS = [
  { chip: 'atmega328p', folder: 'uno', hz: 16_000_000, flash: 32_256, ram: 2048 },
  { chip: 'atmega2560', folder: 'mega', hz: 16_000_000, flash: 253_952, ram: 8192 },
  { chip: 'attiny85', folder: 'tiny', hz: 8_000_000, flash: 8192, ram: 512 },
];

const includes = (text) => [...text.matchAll(/#include\s*[<"]([\w]+)\.h[>"]/g)].map((m) => m[1]);

/** The libraries a sketch needs, following the libraries' own includes. */
function librariesOf(sketch) {
  const found = new Set();
  const visit = (text) => {
    for (const name of includes(text)) {
      const folder = join(here, 'libraries', name);
      if (found.has(name) || !existsSync(folder)) continue;
      found.add(name);
      for (const file of readdirSync(folder)) if (/\.(h|cpp)$/.test(file)) visit(readFileSync(join(folder, file), 'utf8'));
    }
  };
  visit(sketch);
  return [...found];
}

const work = mkdtempSync(join(tmpdir(), 'benchtop-avr-'));
const examples = [];
try {
  console.log(execFileSync('avr-g++', ['--version'], { encoding: 'utf8' }).split('\n')[0]);
  for (const { chip, folder, hz, flash, ram } of CHIPS) {
    const dir = join(here, 'examples', folder);
    for (const file of readdirSync(dir)
      .filter((f) => f.endsWith('.ino'))
      .sort()) {
      const id = basename(file, '.ino');
      const sketch = readFileSync(join(dir, file), 'utf8');
      const libraries = librariesOf(sketch);
      const sources = [
        join(here, 'core', 'core.cpp'),
        ...libraries.flatMap((name) =>
          readdirSync(join(here, 'libraries', name))
            .filter((f) => f.endsWith('.cpp'))
            .map((f) => join(here, 'libraries', name, f)),
        ),
      ];
      const elf = join(work, `${chip}-${id}.elf`);
      execFileSync(
        'avr-g++',
        [
          `-mmcu=${chip}`,
          `-DF_CPU=${hz}UL`,
          '-Os',
          '-std=gnu++11',
          '-fno-exceptions',
          '-fno-threadsafe-statics',
          '-ffunction-sections',
          '-fdata-sections',
          '-Wl,--gc-sections',
          '-Wall',
          '-Wextra',
          '-Wno-unused-parameter',
          `-I${join(here, 'core')}`,
          ...libraries.map((name) => `-I${join(here, 'libraries', name)}`),
          '-include',
          join(here, 'core', 'Arduino.h'),
          '-x',
          'c++',
          join(dir, file),
          ...sources,
          '-o',
          elf,
        ],
        { stdio: 'inherit' },
      );
      const hex = join(work, `${chip}-${id}.hex`);
      execFileSync('avr-objcopy', ['-O', 'ihex', '-R', '.eeprom', elf, hex]);
      const [text, data, bss] = execFileSync('avr-size', [elf], { encoding: 'utf8' }).split('\n')[1].trim().split(/\s+/).map(Number);
      console.log(`${chip} ${id}: ${text + data} bytes of flash, ${data + bss} of RAM${libraries.length ? ` (${libraries.join(', ')})` : ''}`);
      if (text + data > flash) throw new Error(`${id} does not fit the ${chip}'s flash.`);
      // Leave room for the stack.
      if (data + bss > ram - 300) throw new Error(`${id} leaves too little RAM on the ${chip}.`);
      examples.push({ id, chip, sketch, hex: readFileSync(hex, 'utf8') });
    }
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}

const out = join(root, 'src', 'lib', 'circuit', 'avr-examples.ts');
writeFileSync(
  out,
  `/**
 * Example sketches for the AVR boards of the circuit simulator, compiled
 * with avr-gcc and Benchtop's small Arduino-style core (firmware/avr).
 * Generated by firmware/avr/build-examples.mjs; do not edit by hand.
 */
export interface AvrExample {
  readonly id: string;
  /** The chip it was built for: the Uno and Nano share the ATmega328P. */
  readonly chip: 'atmega328p' | 'atmega2560' | 'attiny85';
  readonly sketch: string;
  readonly hex: string;
}

export const AVR_EXAMPLES: readonly AvrExample[] = ${JSON.stringify(examples, null, 2)};
`,
);
console.log(`Wrote ${examples.length} examples to ${out}`);
execFileSync('npx', ['biome', 'format', '--write', out], { cwd: root, stdio: 'ignore' });
